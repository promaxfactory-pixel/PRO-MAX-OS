// PRO MAX OS – Complete project export packager.
// Produces a clean source zip + PROJECT-CONTEXT.md (+ optional concatenated sources)
// to develop the project on Claude AI (claude.ai upload or Claude Code).
//
// Usage:
//   node scripts/export-project.mjs            -> dist/export/PRO-MAX-OS-export.zip + PROJECT-CONTEXT.md
//   node scripts/export-project.mjs --full     -> also builds SOURCES-ALL.md (every source file)
//   node scripts/export-project.mjs --out <dir>
//
// No dependencies. Zip is written by a built-in STORE-method writer, so it works on
// any Node >= 14 without external tools.

import { promises as fs } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(process.cwd());
const args = process.argv.slice(2);
const OUT_DIR = path.resolve(args.includes('--out') ? args[args.indexOf('--out') + 1] : path.join(ROOT, 'dist', 'export'));
const FULL = args.includes('--full');

const EXCLUDED_NAMES = new Set([
  '.git', '.hg', '.svn', 'node_modules', 'target', 'dist', 'gen', 'build', 'out',
  '.webpack', '.turbo', '.cache', '.parcel-cache', '.next', '.nuxt', 'logs', 'tmp',
  '.idea', '.vscode', 'coverage', 'debug',
]);
const EXCLUDED_EXTS = new Set(['.db', '.db-journal', '.db-wal', '.db-shm', '.log', '.zip', '.apk', '.exe', '.dll', '.pdb', '.o', '.rlib', '.rmeta', '.class']);
const TEXT_EXTS = new Set(['.rs', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.json', '.html', '.css', '.sql', '.md', '.toml', '.yml', '.yaml', '.env', '.conf', '.config', '.txt', '.svg', '.xml']);

async function collect(baseDir) {
  const files = [];
  async function walk(dir) {
    let entries;
    try {
      entries = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (EXCLUDED_NAMES.has(e.name)) continue;
        await walk(full);
      } else {
        if (EXCLUDED_EXTS.has(path.extname(e.name).toLowerCase())) continue;
        if (e.name === '.env' || e.name.startsWith('.env.')) continue;
        files.push(path.relative(baseDir, full).replaceAll(path.sep, '/'));
      }
    }
  }
  await walk(baseDir);
  return files.sort();
}

// ── Minimal ZIP writer (STORE method, UTF-8 names) ──────────────────────
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return (c ^ 0xffffffff) >>> 0;
}

function zip(files) {
  const parts = [];
  const central = [];
  let offset = 0;
  for (const f of files) {
    const nameBuf = Buffer.from(f.name, 'utf8');
    const data = f.data;
    const crc = crc32(data);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0);
    lh.writeUInt16LE(20, 4);
    lh.writeUInt16LE(0x0800, 6);
    lh.writeUInt16LE(0, 8);
    lh.writeUInt16LE(0, 10);
    lh.writeUInt16LE(0, 12);
    lh.writeUInt32LE(crc, 14);
    lh.writeUInt32LE(data.length, 18);
    lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(nameBuf.length, 26);
    lh.writeUInt16LE(0, 28);
    const local = Buffer.concat([lh, nameBuf, data]);
    parts.push(local);
    central.push({ nameBuf, crc, size: data.length, offset });
    offset += local.length;
  }
  const cdStart = offset;
  const cdHeaders = central.map((c) => {
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0);
    ch.writeUInt16LE(20, 4);
    ch.writeUInt16LE(20, 6);
    ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(0, 10);
    ch.writeUInt16LE(0, 12);
    ch.writeUInt16LE(0, 14);
    ch.writeUInt32LE(c.crc, 16);
    ch.writeUInt32LE(c.size, 20);
    ch.writeUInt32LE(c.size, 24);
    ch.writeUInt16LE(c.nameBuf.length, 28);
    ch.writeUInt16LE(0, 30);
    ch.writeUInt16LE(0, 32);
    ch.writeUInt16LE(0, 34);
    ch.writeUInt16LE(0, 36);
    ch.writeUInt32LE(0, 38);
    ch.writeUInt32LE(c.offset, 42);
    return Buffer.concat([ch, c.nameBuf]);
  });
  const cdSize = cdHeaders.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(central.length, 8);
  end.writeUInt16LE(central.length, 10);
  end.writeUInt32LE(cdSize, 12);
  end.writeUInt32LE(cdStart, 16);
  end.writeUInt16LE(0, 20);
  return Buffer.concat([...parts, ...cdHeaders, end]);
}

