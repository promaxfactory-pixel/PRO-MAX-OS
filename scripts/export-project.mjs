async function readText(f) {
  try {
    return await fs.readFile(path.join(ROOT, f), 'utf8');
  } catch {
    return '';
  }
}

// ── Main ────────────────────────────────────────────────────────────────
const files = await collect(ROOT);
await fs.mkdir(OUT_DIR, { recursive: true });

const entries = [];
for (const f of files) {
  const buf = await fs.readFile(path.join(ROOT, f));
  entries.push({ name: f, data: buf });
}

const zipPath = path.join(OUT_DIR, 'PRO-MAX-OS-export.zip');
await fs.writeFile(zipPath, zip(entries));

const ctx = await buildContext(files);
await fs.writeFile(path.join(OUT_DIR, 'PROJECT-CONTEXT.md'), ctx);

if (FULL) {
  const all = [];
  for (const f of files) {
    const ext = path.extname(f).toLowerCase();
    if (!TEXT_EXTS.has(ext)) continue;
    const txt = await readText(f);
    all.push(`\n\n/* ===== ${f} ===== */\n\n${txt}`);
  }
  await fs.writeFile(path.join(OUT_DIR, 'SOURCES-ALL.md'), all.join(''));
}

const sizeMB = (entries.reduce((n, e) => n + e.data.length, 0) / 1048576).toFixed(2);
console.log('Exported files:', entries.length, '(' + sizeMB + ' MB raw)');
console.log('ZIP   :', zipPath, '(' + (await fs.stat(zipPath)).size.toFixed(0) + ' bytes)');
console.log('CTX   :', path.join(OUT_DIR, 'PROJECT-CONTEXT.md'));
if (FULL) console.log('FULL  :', path.join(OUT_DIR, 'SOURCES-ALL.md'));
